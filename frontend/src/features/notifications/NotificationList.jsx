import React, { useEffect, useState } from 'react'
import FeedbackMessage from '../../components/FeedbackMessage.jsx'
import { BellIcon } from '../../components/Icons.jsx'
import { listNotifications } from '../../api/notificationApi.js'

function formatTime(ts) {
  if (!ts) return ''
  try {
    const d = new Date(ts)
    if (isNaN(d.getTime())) return String(ts)
    return d.toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'short' })
  } catch {
    return String(ts)
  }
}

export default function NotificationList({ trackingId }) {
  const [data, setData] = useState(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')

  async function load() {
    if (!trackingId?.trim()) {
      setError('Please provide a tracking ID.')
      return
    }
    setLoading(true)
    setError('')
    setData(null)
    try {
      const list = await listNotifications(trackingId.trim())
      setData(list)
    } catch (err) {
      setError(err.message || 'Failed to retrieve notification records.')
    } finally {
      setLoading(false)
    }
  }

  useEffect(() => {
    if (trackingId?.trim()) {
      load()
    } else {
      setData(null)
      setError('')
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [trackingId])

  return (
    <div className="panel-card">
      <div className="panel-header-row">
        <div>
          <h2 className="panel-title">System Dispatch Logs</h2>
          <p className="panel-subtitle">Event notifications generated by the notification microservice.</p>
        </div>
        {trackingId && (
          <button
            type="button"
            className="action-btn btn-secondary btn-sm"
            onClick={load}
            disabled={loading}
          >
            {loading ? 'Refreshing...' : 'Refresh'}
          </button>
        )}
      </div>

      {!trackingId?.trim() ? (
        <FeedbackMessage tone="info">Select or enter a tracking ID to view associated dispatch notifications.</FeedbackMessage>
      ) : (
        <>
          {loading && <div className="loading-state">Querying notification service...</div>}
          {error && <FeedbackMessage tone="error" role="alert">{error}</FeedbackMessage>}

          {data && !loading && !error && (
            data.length === 0 ? (
              <FeedbackMessage tone="info">No notification records found for this tracking ID.</FeedbackMessage>
            ) : (
              <div className="notifications-feed">
                {data.map(n => (
                  <div key={n.id} className="notification-entry">
                    <div className="entry-header">
                      <div className="entry-title-wrap">
                        <BellIcon size={14} className="entry-bell" />
                        <span className="entry-title">{n.title}</span>
                      </div>
                      <span className="entry-time">{formatTime(n.createdAt)}</span>
                    </div>
                    <div className="entry-body">{n.message}</div>
                    <div className="entry-meta-tags">
                      <span className="meta-tag">Status: <strong>{n.status}</strong></span>
                      <span className="meta-tag">Channel: <strong>{n.deliveryState || 'INTERNAL'}</strong></span>
                    </div>
                  </div>
                ))}
              </div>
            )
          )}
        </>
      )}
    </div>
  )
}
